type MailflareBindings = Record<string, unknown>
type WorkerContext = { waitUntil: (promise: Promise<unknown>) => void }
type MailflareWorker = WorkerHandlerSet<MailflareBindings, WorkerContext>

const mailflareEnv = (env: TenantEnv) => asMailflareEnv(env) as MailflareBindings

const mailflare = mailflareWorker as unknown as MailflareWorker

const mailflareMailBridge = createMailflareMailBridge<TenantEnv, WorkerContext>({
  basePath: "/mail",
  defaultLocale: helloAdaSite.defaultLocale,
})

const siteAgentHandlers: WorkerHandlerSet<TenantEnv, WorkerContext> = {
  async fetch(request, env, context) {
    const { pathname } = new URL(request.url)
    if (pathname === "/api/helloada/mail" || pathname.startsWith("/api/helloada/mail/")) {
      if (!mailflare.fetch) throw new Error("Mailflare HTTP handler is missing.")
      return mailflareMailBridge(request, env, context, async (authorizedRequest) =>
        await mailflare.fetch!(authorizedRequest, mailflareEnv(env), context))
    }
    if ((request.method === "GET" || request.method === "HEAD") && (pathname === "/admin/login" || pathname === "/admin/login/")) {
      return Promise.resolve(helloAdaAdminEntry(env.HELLOADA_HANDOFF_ISSUER, env.HELLOADA_TENANT_ID))
    }
    // Managed bases are declared by the tenant and served by Next, not by the
    // stored presentation inventory.
    const managedPaths = (helloAdaSite.routes as unknown as { managedPaths?: unknown }).managedPaths
    if (request.method === "GET" || request.method === "HEAD") {
      // Keep a published trailing-slash URL on the managed page instead of
      // letting Next answer with a 308.
      const rewrite = managedPathRewrite(new URL(request.url).pathname, managedPaths)
      if (rewrite) {
        const url = new URL(request.url)
        url.pathname = rewrite
        request = new Request(url, request)
      }
    }
    const previewMount = helloAdaSite.routes.preview
    const previewPath = previewMount ? workspacePreviewPath(pathname, previewMount) : undefined
    const staticResponse = await staticWebsiteResponse(request, env, previewMount, managedPaths)
    if (staticResponse) return staticResponse
    const handler = openNextWorker as unknown as {
      fetch: (request: Request, env: TenantEnv, context: WorkerContext) => Promise<Response>
    }
    const response = await handler.fetch(request, env, context)
    // Next owns Payload-backed pages and managed bases. The static handler
    // already decorates its own preview responses; every other preview page
    // needs the same containment and framing contract.
    return previewPath !== undefined && previewMount
      ? previewHtmlResponse(response, previewMount, env)
      : response
  },
}

const mailflareOwnerGate = createPayloadOwnerGate<TenantEnv, WorkerContext>({
  basePath: "/mail",
  defaultLocale: helloAdaSite.defaultLocale,
  resolveIdentity: async (request, env, context) => {
    const cookie = request.headers.get("cookie")
    if (!cookie) return null
    const identityRequest = new Request("https://helloada-internal.invalid/api/helloada/mailflare-identity", {
      headers: { accept: "application/json", cookie },
    })
    const response = await (openNextWorker as unknown as {
      fetch: (request: Request, env: TenantEnv, context: WorkerContext) => Promise<Response>
    }).fetch(identityRequest, env, context)
    if (response.status === 401) return null
    if (!response.ok) throw new Error("Payload could not confirm the authenticated owner identity")
    const identity = await response.json() as { subject?: unknown }
    if (typeof identity.subject !== "string" || !identity.subject.trim()) {
      throw new Error("Payload owner identity did not contain a stable subject")
    }
    return { subject: identity.subject.trim() }
  },
  logout: async (request, env, context) => {
    const cookie = request.headers.get("cookie")
    if (!cookie) return new Response(null, { status: 204 })
    const payloadLogout = new Request("https://helloada-internal.invalid/api/users/logout", {
      method: "POST",
      headers: { accept: "application/json", cookie },
    })
    return (openNextWorker as unknown as {
      fetch: (request: Request, env: TenantEnv, context: WorkerContext) => Promise<Response>
    }).fetch(payloadLogout, env, context)
  },
})

export default composeTenantWorker({
  site: siteAgentHandlers,
  mailflare,
  mailflareEnv: asMailflareEnv,
  mailflareRequest: mailflareOwnerGate,
  mailflareQueueNames: (env: TenantEnv) => [
    env.HELLOADA_MAILFLARE_INBOUND_QUEUE_NAME,
    env.HELLOADA_MAILFLARE_OUTBOUND_QUEUE_NAME,
    env.HELLOADA_MAILFLARE_AGENT_QUEUE_NAME,
  ],
  basePath: "/mail",
})

