const fieldFallback = (field: string) => field
  .replace(/([a-z])([A-Z])/g, '$1 $2')
  .replace(/[-_]/g, ' ')
  .replace(/^./, (value) => value.toUpperCase())

export const normalizeAdminLanguage = (value?: string): HelloAdaLanguage => {
  if (value && isHelloAdaLanguage(value)) return value
  const base = value?.split('-')[0]
  if (base && isHelloAdaLanguage(base)) return base
  return DEFAULT_LANGUAGE
}

export const adminText = (key: string, language?: string) => {
  const normalized = normalizeAdminLanguage(language)
  if (key.startsWith('owner.')) return ownerCopy[normalized]?.[key] || ownerCopy.en[key] || key
  if (key.startsWith('growth.')) return growthCopy[normalized]?.[key] || growthCopy.en[key] || key
  return copies[normalized]?.[key] || en[key] || key
}

export const adminFieldLabel = (field: string, language?: string) => {
  const key = `field.${field}`
  return adminText(key, language) === key ? fieldFallback(field) : adminText(key, language)
}

export const adminLanguageLabel = (code: string, language?: string) => {
  const locale = normalizeAdminLanguage(language)
  try {
    return new Intl.DisplayNames([locale, 'en'], { type: 'language' }).of(code) || code
  } catch {
    return code
  }
}

export const adminLabel = (key: string) => ({ i18n }: { i18n?: { language?: string } }) =>
  adminText(key, i18n?.language)

export const adminLanguageOption = (code: string) => ({ i18n }: { i18n?: { language?: string } }) =>
  adminLanguageLabel(code, i18n?.language)

export const adminField = (field: string) => ({ i18n }: { i18n?: { language?: string } }) =>
  adminFieldLabel(field, i18n?.language)
